


function getElementsByTag(tagName) {

  gottenElement = document.getElementsByTagName(tagName)

  return gottenElement
}

function getElementsByClassName(className) {

  gottenClass = document.getElementsByClassName(className)
  return gottenClass
}

function getElementById(tagId) {

  gottenId = document.getElementById(tagId) 
  return gottenId
}


function getElementsByAttribute(tagAttribute) {

  gottenAttribute = document.getElementsByAttribute(tagAttribute)
  return gottenAttribute
}